/*
 * TerraShield — build-standalone.js
 * Makes ONE self-contained file: dist/terrashield.html
 * Everything is inlined (CSS, fonts as data URIs, data, engine, voice, text, app),
 * so it opens by double-click anywhere, fully offline. No packages needed.
 *
 * Run:  node scripts/build-standalone.js      (also runs build-data first)
 */
const fs = require('fs');
const path = require('path');
const root = path.join(__dirname, '..');
const web = path.join(root, 'web');

require('./build-data.js');   // make sure web/js/data.js matches shared/

let html = fs.readFileSync(path.join(web, 'index.html'), 'utf8');

// 1) Inline the stylesheet, turning font files into base64 data URIs.
let css = fs.readFileSync(path.join(web, 'css/styles.css'), 'utf8');
css = css.replace(/url\('\.\.\/assets\/fonts\/([^']+)'\)/g, (m, file) => {
  const b64 = fs.readFileSync(path.join(web, 'assets/fonts', file)).toString('base64');
  return "url('data:font/woff2;base64," + b64 + "')";
});
html = html.replace(/<link rel="stylesheet" href="css\/styles\.css">/, () => '<style>\n' + css + '\n</style>');

// 2) Inline every local <script src="js/...">.
html = html.replace(/<script src="(js\/[^"]+)"><\/script>/g, (m, src) => {
  const js = fs.readFileSync(path.join(web, src), 'utf8').replace(/<\/script/gi, '<\\/script');
  return '<script>/* ' + src + ' */\n' + js + '\n</script>';
});

if (/<script src=|<link rel="stylesheet"/.test(html)) throw new Error('Something was not inlined');

html = html.replace('<!-- TerraShield ·', '<!-- STANDALONE BUILD (generated by scripts/build-standalone.js) · TerraShield ·');
fs.mkdirSync(path.join(root, 'dist'), { recursive: true });
const out = path.join(root, 'dist/terrashield.html');
fs.writeFileSync(out, html, 'utf8');
console.log('✓ dist/terrashield.html written (' + (fs.statSync(out).size / 1024).toFixed(0) + ' KB, fully self-contained)');
