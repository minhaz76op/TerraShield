/*
 * TerraShield — build-data.js
 * Turns the shared JSON files (single source of truth) into web/js/data.js.
 *
 * Why: browsers block fetch() of local JSON when index.html is opened by
 * double-click (file://). A plain <script> file works everywhere, offline.
 *
 * Run:  node scripts/build-data.js
 * Re-run it every time you edit anything in shared/.
 */
const fs = require('fs');
const path = require('path');

const root = path.join(__dirname, '..');
const read = (p) => JSON.parse(fs.readFileSync(path.join(root, p), 'utf8'));

const loc = read('shared/data/locations.json');
const data = {
  district: loc.district,
  upazila: loc.upazila,
  subRegistryOffice: loc.subRegistryOffice,
  mouzas: loc.mouzas,
  people: read('shared/data/people.json').people,
  plots: read('shared/data/plots.json').plots,
  khatians: read('shared/data/khatians.json').khatians,
  deeds: read('shared/data/deeds.json').deeds,
  namjari: read('shared/data/namjari.json').namjari
};
const testCases = read('shared/test-cases.json').cases;
const units = read('shared/units.json');      // land-calculator constants (not used by the rule engine)

const out =
  '/* AUTO-GENERATED by scripts/build-data.js — do not edit by hand.\n' +
  ' * Edit the files in shared/ and run: node scripts/build-data.js\n' +
  ' * FICTIONAL SAMPLE DATA ONLY / শুধুমাত্র কাল্পনিক নমুনা তথ্য */\n' +
  'window.TS = window.TS || {};\n' +
  'window.TS.data = ' + JSON.stringify(data, null, 2) + ';\n' +
  'window.TS.testCases = ' + JSON.stringify(testCases, null, 2) + ';\n' +
  'window.TS.units = ' + JSON.stringify(units, null, 2) + ';\n';

fs.writeFileSync(path.join(root, 'web/js/data.js'), out, 'utf8');
console.log('✓ web/js/data.js written:',
  data.plots.length, 'plots,', data.khatians.length, 'khatians,',
  data.deeds.length, 'deeds,', data.namjari.length, 'namjari,',
  testCases.length, 'test cases');
